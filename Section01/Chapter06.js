// 2. 화살표 함수와 나머지 매개변수
const printNames = (...names) => {
    names.forEach(name => console.log(`이름: ${name}`));
};
printNames("철수", "짱구", "맹구");

// 3. 콜백 함수 실전 예시
const startTask = (taskName, callback) => {
    console.log(`${taskName} 작업 시작...`);
    // 작업이 끝났다고 가정하고 콜백 호출
    callback();
};

startTask("데이터 분석", () => {
    console.log("작업이 완료되었습니다!");
});